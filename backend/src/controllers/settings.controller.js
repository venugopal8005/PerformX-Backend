const syncAdAccountsForConnection = async ({ agencyId, connectionId }) => {
  const connection = await MetaConnection.findOne({
    _id: connectionId,
    agency_id: agencyId,
    client_id: null,
    is_active: true,
  }).select("+access_token +access_token_encrypted");

  if (!connection) {
    throw new Error("Active Meta connection not found");
  }

  if (connection.token_expires_at && connection.token_expires_at <= new Date()) {
    connection.status = "expired";
    connection.is_active = false;
    connection.last_error = "Meta token expired. Reconnect this profile.";
    await connection.save();
    throw new Error("Meta token expired. Reconnect this profile.");
  }

  const accessToken = getMetaAccessToken(connection);
  if (!accessToken) {
    throw new Error("Meta token missing. Reconnect this profile.");
  }

  try {
    const accounts = await fetchAllAccessibleMetaAdAccounts(accessToken);
    const now = new Date();
    const synced = [];
    let newCount = 0;

    for (const account of accounts) {
      const adAccountId =
        account.id ||
        (account.account_id
          ? `act_${String(account.account_id).replace(/^act_/, "")}`
          : null);

      if (!adAccountId) continue;

      const existed = await MetaAdAccount.exists({
        agency_id: agencyId,
        ad_account_id: adAccountId,
      });

      const syncedAccount = await MetaAdAccount.findOneAndUpdate(
        {
          agency_id: agencyId,
          ad_account_id: adAccountId,
        },
        {
          $set: {
            meta_connection_id: connection._id,
            name: account.name || adAccountId,
            currency: account.currency || null,
            timezone_name: account.timezone_name || null,
            account_status:
              account.account_status !== undefined
                ? String(account.account_status)
                : null,
            last_synced_at: now,
            last_seen_at: now,
            is_accessible: true,
            is_active: true,
          },
          $setOnInsert: {
            agency_id: agencyId,
            client_id: null,
          },
        },
        { upsert: true, new: true, setDefaultsOnInsert: true }
      );

      if (!existed) newCount += 1;
      synced.push(syncedAccount);
    }

    const seenAccountIds = synced.map((account) => account.ad_account_id);
    await MetaAdAccount.updateMany(
      {
        agency_id: agencyId,
        meta_connection_id: connection._id,
        ...(seenAccountIds.length
          ? { ad_account_id: { $nin: seenAccountIds } }
          : {}),
      },
      { $set: { is_accessible: false } }
    );

    connection.status = deriveConnectionStatus({
      ...connection.toObject(),
      status: "active",
      is_active: true,
    });
    connection.last_synced_at = now;
    connection.last_error = null;
    await connection.save();

    return {
      accounts: synced,
      newCount,
    };
  } catch (err) {
    connection.status = "permission_error";
    connection.last_error = err.message;
    await connection.save();
    throw err;
  }
};

