export const updateProfile = async (req, res) => {
  try {
    const agencyId = requireAgency(req, res);
    if (!agencyId) return;

    const userId = getUserId(req);
    const userUpdates = pickDefined(req.body, ["full_name", "avatar_url"]);

    if (req.body.fullName !== undefined) {
      userUpdates.full_name = req.body.fullName;
    }

    const [user, settings] = await Promise.all([
      Object.keys(userUpdates).length
        ? User.findOneAndUpdate(
            { _id: userId, agency_id: agencyId },
            userUpdates,
            { new: true, runValidators: true }
          )
        : User.findOne({ _id: userId, agency_id: agencyId }),
      UserSettings.findOneAndUpdate(
        { agency_id: agencyId, user_id: userId },
        {
          $set: pickDefined(req.body, ["timezone", "currency"]),
          $setOnInsert: { agency_id: agencyId, user_id: userId },
        },
        { upsert: true, new: true, setDefaultsOnInsert: true, runValidators: true }
      ),
    ]);

    if (!user) {
      return res.status(404).json({
        success: false,
        message: "User not found",
      });
    }

    return res.json({
      success: true,
      profile: serializeUser(user, settings),
    });
  } catch (err) {
    return res.status(500).json({
      success: false,
      message: err.message || "Failed to update profile settings",
    });
  }
};

