export const updateWorkspace = async (req, res) => {
  try {
    const agencyId = requireAgency(req, res);
    if (!agencyId) return;

    const agencyName = req.body.name !== undefined ? String(req.body.name).trim() : null;
    const settingsUpdates = pickDefined(req.body, [
      "logo_url",
      "default_sender_name",
      "reply_to_email",
      "from_email",
      "custom_domain_status",
      "default_timezone",
      "default_currency",
      "report_footer_branding",
      "show_narrative_branding",
      "include_agency_name_in_footer",
      "include_generated_timestamp",
      "include_data_disclaimer",
      "report_email_tone",
    ]);
    const isOwner = req.workspaceMembership?.role === "owner" || req.user?.role === "owner";

    if (Object.prototype.hasOwnProperty.call(req.body, "logo_url") && !isOwner) {
      return res.status(403).json({
        success: false,
        message: "Only workspace owners can change the workspace logo.",
      });
    }

    const agency = await Agency.findById(agencyId);

    if (!agency) {
      return res.status(404).json({
        success: false,
        message: "Workspace not found",
      });
    }

    if (agencyName) {
      agency.name = agencyName;
      await agency.save();
    }

    const settings = await WorkspaceSettings.findOneAndUpdate(
      { agency_id: agencyId },
      {
        $set: settingsUpdates,
        $setOnInsert: { agency_id: agencyId },
      },
      { upsert: true, new: true, setDefaultsOnInsert: true, runValidators: true }
    );

    return res.json({
      success: true,
      workspace: serializeWorkspace(agency, agencyId, settings),
    });
  } catch (err) {
    return res.status(500).json({
      success: false,
      message: err.message || "Failed to update workspace settings",
    });
  }
};

const escapeHtml = (value = "") =>
  String(value)
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
